#!/usr/bin/env python3
"""Generate a read-only ONTAP REST API reference from NetApp's ontap-mcp API catalog
(github.com/NetApp/ontap-mcp, file conf/ontap_api_catalog.json, Apache-2.0).

Usage (from repo root):
    python3 scripts/gen_ontap_catalog_docs.py <path/to/ontap_api_catalog.json>

Writes managing-netapp-production/references/ontap-api/:
    endpoints.md       every GET collection endpoint in the catalog, by area, with the ONTAP version it appeared in
    areas/<area>.md    per endpoint: path parameters, filters and fields (with "since" versions)
    spec/<file>        the catalog itself (copied, unmodified)
README.md, python-dev-guide.md and NOTICE.md are hand-written and not overwritten.
The catalog covers GET only. For POST/PATCH/DELETE, use the cluster's own spec (scripts/gen_api_docs.py ontap).
"""
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "managing-netapp-production" / "references" / "ontap-api"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def short(text, n=220):
    t = re.sub(r"\[([^\]]*)\]\(#[^)\s]*\)?", r"\1", text or "")  # catalog anchors (often truncated)
    t = re.sub(r"\s+", " ", t).strip().replace("|", "\\|")
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "…"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    cat = json.loads(src.read_text())
    ver, eps = cat.get("ontap_version", "?"), cat["endpoints"]
    (OUT / "areas").mkdir(parents=True, exist_ok=True)
    (OUT / "spec").mkdir(parents=True, exist_ok=True)
    for old in (OUT / "areas").glob("*.md"):
        old.unlink()
    if src.resolve() != (OUT / "spec" / src.name).resolve():
        shutil.copy(src, OUT / "spec" / src.name)

    by_tag = {}
    for path, e in eps.items():
        for t in e.get("tags") or ["Other"]:
            by_tag.setdefault(t, []).append((path, e))

    header = (f"<!-- GENERATED by scripts/gen_ontap_catalog_docs.py from {src.name} (ONTAP {ver}, generated "
              f"{cat.get('generated_at', '?')}). Do not edit by hand; regenerate. -->\n")
    note = (f"> Source: NetApp's **ontap-mcp** API catalog for **ONTAP {ver}** (github.com/NetApp/ontap-mcp, Apache-2.0, "
            "see NOTICE.md). It lists **GET endpoints only**, with their filters and fields. Everything here is `[doc]` for "
            f"reads on ONTAP {ver}; a field marked *since X* doesn't exist before ONTAP X. For writes (POST/PATCH/DELETE), "
            "use the cluster's own spec (README.md, *Full API locally*). Paths are relative to `https://<cluster-mgmt>/api`.\n")

    L = [header, f"# ONTAP REST API {ver}: read-only endpoint index", "", note,
         f"{len(eps)} GET endpoints in {len(by_tag)} areas. All are T0 (read).", ""]
    for t in sorted(by_tag):
        L += [f"## [{t}](areas/{slug(t)}.md)", "", "| Path | Summary | Since |", "|---|---|---|"]
        for path, e in sorted(by_tag[t]):
            L.append(f"| `/api{path}` | {short(e.get('summary'), 110)} | {e.get('api_introduced', '')} |")
        L.append("")
    (OUT / "endpoints.md").write_text("\n".join(L))

    for t, items in by_tag.items():
        A = [header, f"# {t} (ONTAP REST API {ver}, GET only)", "", note, "[← endpoint index](../endpoints.md)", ""]
        for path, e in sorted(items):
            A += [f"## GET `/api{path}`", "", f"**Tier:** T0 · **since ONTAP** {e.get('api_introduced', '?')}", "",
                  short(e.get("summary"), 600), ""]
            if e.get("path_params"):
                pp = e["path_params"]
                names = pp if isinstance(pp, list) else list(pp)
                A += ["**Path parameters:** " + ", ".join(f"`{p}`" for p in names), ""]
            if e.get("filters"):
                A += ["**Filters** (query `<field>=<value>`):", "", "| Filter | Type | Since | Description |", "|---|---|---|---|"]
                for f, m in sorted(e["filters"].items()):
                    A.append(f"| `{f}` | {m.get('type', '')} | {m.get('since', '')} | {short(m.get('desc'))} |")
                A.append("")
            if e.get("fields"):
                A += ["**Fields** (request with `fields=a,b.c`):", "", "| Field | Since | Description |", "|---|---|---|"]
                for f, m in sorted(e["fields"].items()):
                    A.append(f"| `{f}` | {m.get('since', '')} | {short(m.get('desc'))} |")
                A.append("")
        (OUT / "areas" / f"{slug(t)}.md").write_text("\n".join(A))
    print(f"ONTAP {ver}: {len(eps)} GET endpoints, {len(by_tag)} areas -> {OUT}")


if __name__ == "__main__":
    main()
