#!/usr/bin/env python3
"""Check that every docker/kubectl/helm/terraform/argocd/flux/promtool/icinga2/monaco command written in a
DevOps skill only uses flags listed in that skill's generated catalogs (scripts/gen_cli_catalogs.py).

Run from the repo root: python3 scripts/check_cli_flags.py   (exit 1 on any undocumented flag)
"""
import os
import sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import re,glob,collections
cats=collections.defaultdict(dict)
for f in glob.glob('managing-*/references/*-command-catalog.md'):
    for l in open(f):
        m=re.match(r'^\| `([^`]+)` \| (.*?) \|',l)
        if m:
            tool=m.group(1).split()[0]
            cats[tool].setdefault(m.group(1),set()).update(re.findall(r'`([^`]+)`',m.group(2)))
TOOLS=('docker','kubectl','helm','terraform','argocd','flux','promtool','icinga2','monaco')
skills=sorted({f.split('/')[0] for f in glob.glob('managing-*/references/*-command-catalog.md') if 'GENERATED by scripts/gen_cli_catalogs.py' in open(f).read()})
issues=0
for sk in skills:
    for f in glob.glob(sk+'/SKILL.md')+glob.glob(sk+'/references/*.md'):
        if 'catalog' in f or f.endswith(('change-gate.md','command-verification.md','incident-comms.md','upgrade-checklist.md')) and 'Platform notes' not in open(f).read(): continue
        for n,line in enumerate(open(f),1):
            for frag in re.findall(r'`([^`]+)`',line)+([line.strip()] if line.startswith(tuple(TOOLS)) else []):
                for m in re.finditer(r'\b('+'|'.join(TOOLS)+r')\b((?:\s+[^\s|`]+)*)',frag):
                    tool=m.group(1); raw=m.group(2).split(); words=[tool]; skip=False
                    for i,w in enumerate(raw):
                        if skip: skip=False; continue
                        if w in ('--context','-n','--namespace','--kube-context','-f','--file','--alertmanager.url') and i+1<len(raw) and raw[i+1].startswith('<'):
                            words.append(w); skip=True; continue
                        if w.startswith('<') or w.startswith('$') or w in ('>',';','&&','|'): 
                            if w in (';','&&','|'): break
                            continue
                        words.append(w)
                    glob_fl=[w for w in words[1:] if w.startswith('-')]
                    path_words=[tool]+[w for w in words[1:] if not w.startswith('-') and not re.match(r'^[\w.-]+/[\w.<>-]+$',w) and '=' not in w]
                    words=path_words+glob_fl
                    # longest command path present
                    best=None
                    for k in range(len(words),0,-1):
                        cand=' '.join(w for w in words[:k])
                        if cand in cats[tool]: best=cand; break
                    if not best: continue
                    sub=[w for w in words[1:len(best.split())]]
                    flags=[re.split(r'[=\s]',w)[0] for w in words[len(best.split()):] if re.match(r'^-{1,2}[a-zA-Z]',w)]
                    # allowed flags: this command + its ancestors
                    allowed=set()
                    parts=best.split()
                    for k in range(1,len(parts)+1): allowed|=cats[tool].get(' '.join(parts[:k]),set())
                    if tool=='kubectl': allowed|=cats[tool].get('kubectl',set())
                    bad=[x for x in flags if x not in allowed]
                    nxt=words[len(parts)] if len(words)>len(parts) else ''
                    if bad:
                        issues+=1; print(f'{f}:{n}: `{best}` unknown flags {bad}')
print(f'check_cli_flags: {issues} undocumented flag(s)')
sys.exit(1 if issues else 0)
